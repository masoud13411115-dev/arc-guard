// ─────────────────────────────────────────────────────────────────────────────
// Context
// ─────────────────────────────────────────────────────────────────────────────
interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  dir: "rtl" | "ltr";
  isRTL: boolean;
}

const I18nContext = createContext<I18nCtx>({
  lang: "fa",
  setLang: () => {},
  t: (k) => k,
  dir: "rtl",
  isRTL: true,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (stored && dict[stored]) return stored;
    return "fa";
  });

  const langMeta = LANGUAGES.find((l) => l.code === lang)!;
  const dir = langMeta.dir;
  const isRTL = dir === "rtl";

  // Apply dir to <html> so scrollbars and browser UI adapt
  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = lang;
  }, [dir, lang]);

  const setLang = (l: Lang) => {
    localStorage.setItem(STORAGE_KEY, l);
    setLangState(l);
  };

  const t = (key: string, vars?: Record<string, string | number>): string => {
    const langDict = dict[lang];
    const faDict   = dict["fa"];
    const raw = langDict[key] ?? faDict[key];
    if (raw === undefined) {
      console.warn(`[i18n] missing key: "${key}" (lang=${lang})`);
    }
    let str = raw ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, String(v));
      });
    }
    return str;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir, isRTL }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
